import assert from 'node:assert/strict';
import {polygon,segments,contained,area,unionArea,distance} from '../dist/geometry.js';
const rect=(id,x,y,w,h)=>({id,x,y,w,h,rotation:0,type:'rect',layer:'foundation'});
const a=rect('a',0,0,20,20),b=rect('b',20,5,10,10);
assert.equal(area(polygon(a)),400);
assert.equal(area(polygon({...a,type:'triangle'})),200);
assert(Math.abs(area(polygon({...a,rotation:37}))-400)<1e-8);
assert.equal(unionArea([a,rect('overlap',10,0,20,20)]),600);
assert.equal(unionArea([a,b]),500);
let ws=segments([a,b]);assert.equal(ws.length,9);assert.equal(ws.filter(w=>w.owners.length===2).length,1);
assert(ws.some(w=>distance(w.a,w.b)===5));
const edge=ws.find(w=>w.owners.length===2);edge.enabled=true;
let after=segments([a,b,rect('c',20,8,5,4)],ws);assert(after.filter(w=>w.enabled).length>=3);
let solo=segments([a]);solo[0].enabled=true;
assert(segments([{...a,x:50,rotation:90}],solo).some(w=>w.enabled));
assert(contained({...rect('s',5,5,5,5),layer:'section'},[a]));
assert(!contained(rect('s',18,18,5,5),[a]));
assert(contained(rect('s',18,8,5,5),[a,b]));
assert(!contained(rect('s',18,1,5,5),[a,b]));
const hole=[rect('t',0,0,10,2),rect('l',0,2,2,6),rect('r',8,2,2,6),rect('b',0,8,10,2)];
assert(!contained(rect('s',1,1,8,8),hole));
const tri={...rect('tri',0,0,20,20),type:'triangle',rotation:30};assert.equal(segments([tri]).length,3);
assert(Math.abs(unionArea([tri])-200)<1e-7);
const crossing=[rect('a',0,0,10,10),{...rect('b',5,0,10,10),rotation:45}];
assert(segments(crossing).length>8);
console.log('Passed: rotated shape areas, union footprint, shared walls, T-joints, wall subdivision, wall persistence, containment across foundations, holes, triangle edges, crossings.');
